/** Ключ предложения: без регистра, ё = е, без знаков препинания — так «Готово!» и «готово» совпадут. */
export const lineKey = (s) => s.toLowerCase().replace(/ё/g, 'е').replace(/[^a-zа-я0-9 ]+/g, ' ').replace(/\s+/g, ' ').trim();

/** Разбить фразу на предложения (как их записывали). «сад посажен!.» → «сад посажен!». */
export const splitSentences = (text) => String(text).replace(/!\./g, '!').split(/(?<=[.!?…])\s+/).map((s) => s.trim()).filter(Boolean);
