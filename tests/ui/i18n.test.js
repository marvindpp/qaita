import { describe, it, expect, beforeAll } from 'vitest';

let tr, setLang;
beforeAll(async () => {
  globalThis.localStorage = { getItem: () => null, setItem() {} };
  globalThis.document = { documentElement: {} };
  ({ tr, setLang } = await import('../../src/ui/i18n.js'));
  setLang('kk');
});

describe('қазақша', () => {
  it('точная фраза', () => expect(tr('Покажите ладонь')).toBe('Алақаныңызды көрсетіңіз'));
  it('числа подставляются', () => expect(tr('Упражнение 2 из 5')).toBe('Жаттығу 2/5'));
  it('эмодзи и пробелы по краям сохраняются', () => expect(tr('  🔗 Ссылка для врача ')).toBe('  🔗 Дәрігерге сілтеме '));
  it('составная фраза — по предложениям', () => expect(tr('Слишком быстро. Медленнее!')).toBe('Тым жылдам. Баяуырақ!'));
  it('имя', () => expect(tr('Здравствуйте, Айгуль!')).toBe('Сәлеметсіз бе, Айгуль!'));
  it('имя с аватаром', () => expect(tr('👵 Здравствуйте, Айгуль!')).toBe('👵 Сәлеметсіз бе, Айгуль!'));
  it('пальцы', () => expect(tr('Указательный и мизинец согнуты')).toBe('Сұқ саусақ мен шынашақ бүгілген'));
  it('ошибки в отчёте', () => expect(tr('наклон корпуса вперёд ×2, подъём плеча к уху ×1')).toBe('денені алға еңкейту ×2, иықты құлаққа көтеру ×1'));
  it('неизвестное — как есть', () => expect(tr('Какая-то новая фраза')).toBe('Какая-то новая фраза'));
  it('русский режим ничего не трогает', () => { setLang('ru'); expect(tr('Покажите ладонь')).toBe('Покажите ладонь'); setLang('kk'); });
});
